#!/usr/bin/env bash
# regenerate inc/phlop/os/kul_mem.hpp, a single file bundle of mkn.kul's
#  inc/mkn/kul/mem.hpp and its per-OS inc/mkn/kul/os/{nix,bsd,win}/mem.hpp headers
#  usage: ./sh/sync_kul_mem.sh [path/to/mkn/kul]   (default /mkn/r/mkn/kul/master)

CWD="$( cd "$( dirname "${BASH_SOURCE[0]}" )" && pwd )" && cd "$CWD"/..
set -e

KUL="${1:-/mkn/r/mkn/kul/master}"
DST="inc/phlop/os/kul_mem.hpp"

python3 - "$KUL/inc/mkn/kul" "$DST" <<'PY'
import re
import sys

src, dst = sys.argv[1:]

ns_open = "namespace mkn {\nnamespace kul {\nnamespace mem {\n"
ns_close = "}  // namespace mem\n}  // namespace kul\n}  // namespace mkn\n"


def read(path):
    with open(f"{src}/{path}") as f:
        s = f.read()
    license, body = s.split("*/\n", 1)
    assert s.count(ns_open) == 1 and s.count(ns_close) == 1, f"unexpected layout {path}"
    body = body.replace("// IWYU pragma: private, include \"mkn/kul/mem.hpp\"\n", "")
    body = body.replace(ns_open, "namespace phlop::os::kul_mem {\n")
    body = body.replace(ns_close, "}  // namespace phlop::os::kul_mem\n")
    body = body.replace("MKN_KUL_", "_PHLOP_KUL_")
    return license + "*/\n", body.strip("\n")


license, main = read("mem.hpp")
_, nix = read("os/nix/mem.hpp")
_, bsd = read("os/bsd/mem.hpp")
_, win = read("os/win/mem.hpp")

dispatch = re.compile(r"#if _PHLOP_KUL_IS_NIX\n.*?\n#endif\n", re.S)
assert len(dispatch.findall(main)) == 1, "unexpected platform dispatch in mem.hpp"
platforms = (  # mirrors MKN_KUL_IS_* from mkn/kul/defs.hpp
    "#if defined(_WIN32)\n\n" + win + "\n\n"
    "#elif defined(__APPLE__) || defined(__NetBSD__) || defined(__FreeBSD__)\n\n" + bsd + "\n\n"
    "#else\n\n" + nix + "\n\n#endif\n"
)
main = dispatch.sub(lambda _: platforms, main)
main = main.replace('#include "mkn/kul/defs.hpp"\n\n', "")

out = (
    "// GENERATED by sh/sync_kul_mem.sh from mkn.kul inc/mkn/kul/mem.hpp - DO NOT EDIT\n"
    "//  used when mkn.kul is not on the include path, see phlop/os/mem.hpp\n\n"
    + license + main + "\n"
)
assert "mkn" not in out.split("*/", 1)[1].split("GENERATED")[-1].replace("mkn.kul", ""), "leftover mkn reference"
with open(dst, "w") as f:
    f.write(out)
print(f"wrote {dst}")
PY
